-- Export configuration to JSON file
local function exportConfig()
    log("Exporting region configuration...")

    local success, err = pcall(function()
        local filename = RegionManager.Config.ExportPath
        local writer = getFileWriter(filename, true, false)

        if not writer then
            log("ERROR: Could not open file for writing: " .. filename)
            return
        end

        -- Build JSON manually (simple format)
        writer:write("{\n")
        writer:write('  "version": "1.0",\n')
        writer:write('  "exportDate": "' .. os.date("%Y-%m-%d %H:%M:%S") .. '",\n')
        writer:write('  "regions": [\n')

        for i, region in ipairs(RegionManager.Config.Regions) do
            writer:write("    {\n")
            writer:write('      "id": "' .. region.id .. '",\n')
            writer:write('      "name": "' .. region.name .. '",\n')
            writer:write('      "x": ' .. region.x .. ',\n')
            writer:write('      "y": ' .. region.y .. ',\n')
            writer:write('      "z": ' .. region.z .. ',\n')
            writer:write('      "width": ' .. region.width .. ',\n')
            writer:write('      "height": ' .. region.height .. ',\n')
            writer:write('      "enabled": ' .. tostring(region.enabled) .. ',\n')
            writer:write('      "categories": [')
            for j, cat in ipairs(region.categories) do
                writer:write('"' .. cat .. '"')
                if j < #region.categories then
                    writer:write(", ")
                end
            end
            writer:write("]\n")
            writer:write("    }")
            if i < #RegionManager.Config.Regions then
                writer:write(",")
            end
            writer:write("\n")
        end

        writer:write("  ]\n")
        writer:write("}\n")
        writer:close()

        log("Configuration exported successfully to: " .. filename)
    end)

    if not success then
        log("ERROR exporting config: " .. tostring(err))
    end
end

local function deleteHotRegion(player, args)
    if player:getAccessLevel() == "None" then
        log("WARNING: Non-admin player " .. player:getUsername() .. " tried to delete a region")
        sendServerCommand(player, "RegionManager", "RegionDeleteFailed", {
            reason = "Admin access required"
        })
        return
    end

    local originalId = args.originalId
    if not originalId or originalId == "" then
        sendServerCommand(player, "RegionManager", "RegionDeleteFailed", {
            reason = "Original region ID is required"
        })
        return
    end

    local currentRegions = loadRegionsFromFile()
    local targetIndex = nil
    local deletedRegion = nil
    for idx, existing in ipairs(currentRegions) do
        if existing.id == originalId then
            targetIndex = idx
            deletedRegion = existing
            break
        end
    end

    if not targetIndex then
        sendServerCommand(player, "RegionManager", "RegionDeleteFailed", {
            reason = "Region '" .. originalId .. "' not found"
        })
        return
    end

    table.remove(currentRegions, targetIndex)

    local writeOk = writeRegionsFile(currentRegions)
    if not writeOk then
        sendServerCommand(player, "RegionManager", "RegionDeleteFailed", {
            reason = "Failed to write regions file"
        })
        return
    end

    log("Region '" .. originalId .. "' deleted by " .. player:getUsername() .. ", re-initializing all zones...")
    registerAllRegions()

    local payload = buildZoneBoundariesPayload()
    RegionManager.Server._cachedBoundariesPayload = payload
    local allPlayers = getOnlinePlayers()
    for i = 0, allPlayers:size() - 1 do
        local p = allPlayers:get(i)
        sendServerCommand(p, "RegionManager", "AllZoneBoundaries", payload)
    end

    sendServerCommand(player, "RegionManager", "RegionDeleted", {
        id = originalId,
        name = deletedRegion and deletedRegion.name or originalId
    })
    log("Region '" .. originalId .. "' successfully deleted and broadcast to " .. allPlayers:size() .. " players")

end

local function updateHotRegion(player, args)
    if player:getAccessLevel() == "None" then
        log("WARNING: Non-admin player " .. player:getUsername() .. " tried to update a region")
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "Admin access required"
        })
        return
    end

    local originalId = args.originalId
    local id = args.id
    local name = args.name
    if not originalId or originalId == "" then
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "Original region ID is required"
        })
        return
    end
    if not id or id == "" or not name or name == "" then
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "Region ID and name are required"
        })
        return
    end
    if not args.x1 or not args.y1 or not args.x2 or not args.y2 then
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "All four coordinates are required"
        })
        return
    end

    local currentRegions = loadRegionsFromFile()
    local targetIndex = nil
    for idx, existing in ipairs(currentRegions) do
        if existing.id == originalId then
            targetIndex = idx
            break
        end
    end

    if not targetIndex then
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "Region '" .. originalId .. "' not found"
        })
        return
    end

    for idx, existing in ipairs(currentRegions) do
        if idx ~= targetIndex and existing.id == id then
            sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
                reason = "Region ID '" .. id .. "' already exists"
            })
            return
        end
    end

    currentRegions[targetIndex] = {
        id = id,
        name = name,
        x1 = args.x1,
        y1 = args.y1,
        x2 = args.x2,
        y2 = args.y2,
        z = args.z or 0,
        enabled = args.enabled ~= false,
        categories = args.categories or {},
        customProperties = args.customProperties or {}
    }

    local writeOk = writeRegionsFile(currentRegions)
    if not writeOk then
        sendServerCommand(player, "RegionManager", "RegionUpdateFailed", {
            reason = "Failed to write regions file"
        })
        return
    end

    log("Region '" .. originalId .. "' updated by " .. player:getUsername() .. ", re-initializing all zones...")
    registerAllRegions()

    local payload = buildZoneBoundariesPayload()
    RegionManager.Server._cachedBoundariesPayload = payload
    local allPlayers = getOnlinePlayers()
    for i = 0, allPlayers:size() - 1 do
        local p = allPlayers:get(i)
        sendServerCommand(p, "RegionManager", "AllZoneBoundaries", payload)
    end

    sendServerCommand(player, "RegionManager", "RegionUpdated", {
        id = id,
        name = name,
        originalId = originalId
    })
    log("Region '" .. originalId .. "' successfully updated (new id='" .. id .. "') and broadcast to " ..
            allPlayers:size() .. " players")

end
local function addHotRegion(player, args)
    -- Admin command to add a new region live
    if player:getAccessLevel() == "None" then
        log("WARNING: Non-admin player " .. player:getUsername() .. " tried to add a region")
        sendServerCommand(player, "RegionManager", "RegionAddFailed", {
            reason = "Admin access required"
        })
        return
    end

    -- Validate required fields
    local id = args.id
    local name = args.name
    if not id or id == "" or not name or name == "" then
        sendServerCommand(player, "RegionManager", "RegionAddFailed", {
            reason = "Region ID and name are required"
        })
        return
    end
    if not args.x1 or not args.y1 or not args.x2 or not args.y2 then
        sendServerCommand(player, "RegionManager", "RegionAddFailed", {
            reason = "All four coordinates are required"
        })
        return
    end

    -- Load current regions from file
    local currentRegions = loadRegionsFromFile()

    -- Check for duplicate ID
    for _, existing in ipairs(currentRegions) do
        if existing.id == id then
            sendServerCommand(player, "RegionManager", "RegionAddFailed", {
                reason = "Region ID '" .. id .. "' already exists"
            })
            return
        end
    end

    -- Build new region definition
    local newRegion = {
        id = id,
        name = name,
        x1 = args.x1,
        y1 = args.y1,
        x2 = args.x2,
        y2 = args.y2,
        z = args.z or 0,
        enabled = args.enabled ~= false,
        categories = args.categories or {},
        customProperties = args.customProperties or {}
    }

    -- Append and save to file
    table.insert(currentRegions, newRegion)
    local writeOk = writeRegionsFile(currentRegions)
    if not writeOk then
        sendServerCommand(player, "RegionManager", "RegionAddFailed", {
            reason = "Failed to write regions file"
        })
        return
    end

    log("Region '" .. id .. "' added by " .. player:getUsername() .. ", re-initializing all zones...")

    -- Hot-swap: re-run full initialization (cleanup + reload + register)
    registerAllRegions()

    -- Broadcast updated zone boundaries to ALL connected players
    local payload = buildZoneBoundariesPayload()
    RegionManager.Server._cachedBoundariesPayload = payload

    local allPlayers = getOnlinePlayers()
    for i = 0, allPlayers:size() - 1 do
        local p = allPlayers:get(i)
        sendServerCommand(p, "RegionManager", "AllZoneBoundaries", payload)
    end

    -- Confirm to the requesting admin
    sendServerCommand(player, "RegionManager", "RegionAdded", {
        id = id,
        name = name
    })
    log("Region '" .. id .. "' successfully added and broadcast to " .. allPlayers:size() .. " players")

end

-- Handle server commands
---@param module string
---@param command string
---@param player IsoPlayer
---@param args table
local function OnClientCommand(module, command, player, args)
    if module ~= "RegionManager" then
        return
    end

    if command == "RequestAllBoundaries" then
        -- Build the zone list once and reuse it until the registered-zones
        -- table mutates (registerAllRegions runs at startup, admin reloads,
        -- etc.). Without this cache every client's RequestAllBoundaries -- and
        -- the throttled retries that happen while zone data is in flight --
        -- would rebuild the same table from scratch.
        local payload = RegionManager.Server._cachedBoundariesPayload
        if not payload then
            payload = buildZoneBoundariesPayload()
            RegionManager.Server._cachedBoundariesPayload = payload
            print("Apocalipse_TSY: Built zone boundaries payload (" .. #payload.zones .. " zones, cached)")
        end

        sendServerCommand(player, "RegionManager", "AllZoneBoundaries", payload)

        print("Sent " .. #payload.zones .. " zone boundaries to " .. player:getUsername())

    elseif command == "RequestZoneInfo" then
        -- Send zone info to client
        local x = args.x
        local y = args.y

        -- Find which zones contain this point using pre-calculated bounds
        local zonesAtLocation = {}

        for id, data in pairs(RegionManager.Server.registeredZones or {}) do
            local bounds = data.bounds
            -- Fast AABB collision check using pre-calculated bounds
            if x >= bounds.minX and x <= bounds.maxX and y >= bounds.minY and y <= bounds.maxY then
                table.insert(zonesAtLocation, {
                    id = data.region.id,
                    name = data.region.name,
                    categories = data.region.categories
                })
            end
        end

        sendServerCommand(player, "RegionManager", "ZoneInfo", {
            zones = zonesAtLocation
        })
    elseif command == "ClientZoneEntered" then
        -- Client detected zone entry, sync with other players
        local zoneId = args.zoneId
        local zoneName = args.zoneName
        local isPvpZone = args.isPvpZone
        local isSafeZone = args.isSafeZone
        local safetyEnabled = args.safetyEnabled

        print("[DEBUG SERVER] Player " .. player:getUsername() .. " entered zone: " .. zoneName .. " (PVP=" ..
                  tostring(isPvpZone) .. ", Safe=" .. tostring(isSafeZone) .. ")")

        -- Broadcast PVP state change to all other players for skull icon sync
        -- local allPlayers = getOnlinePlayers()
        -- for i = 0, allPlayers:size() - 1 do
        --     local otherPlayer = allPlayers:get(i)
        --     if otherPlayer ~= player then
        --         sendServerCommand(otherPlayer, "RegionManager", "PlayerPvpStateChanged", {
        --             playerIndex = player:getPlayerNum(),
        --             pvpEnabled = isPvpZone,
        --             safetyEnabled = safetyEnabled
        --         })
        --     end
        -- end
        print("[DEBUG SERVER] Broadcasted zone entry to " .. (allPlayers:size() - 1) .. " other players")

    elseif command == "ClientZoneExited" then
        -- Client detected zone exit, sync with other players
        -- local zoneId = args.zoneId
        -- local zoneName = args.zoneName
        -- local safetyEnabled = args.safetyEnabled

        print("[DEBUG SERVER] Player " .. player:getUsername() .. " exited zone: " .. zoneName)

        -- Send zone exited notification to the player
        -- sendServerCommand(player, "RegionManager", "ZoneExited", {
        --     id = zoneId,
        --     name = zoneName,
        --     safetyEnabled = safetyEnabled
        -- })

        -- Broadcast PVP state reset to all other players
        -- local allPlayers = getOnlinePlayers()
        -- for i = 0, allPlayers:size() - 1 do
        --     local otherPlayer = allPlayers:get(i)
        --     if otherPlayer ~= player then
        --         sendServerCommand(otherPlayer, "RegionManager", "PlayerPvpStateChanged", {
        --             playerIndex = player:getPlayerNum(),
        --             pvpEnabled = false,
        --             safetyEnabled = safetyEnabled
        --         })
        --     end
        -- end
        -- print("[DEBUG SERVER] Broadcasted zone exit to " .. (allPlayers:size() - 1) .. " other players")

    elseif command == "AddRegion" then
        addHotRegion(player, args)
    elseif command == "UpdateRegion" then
        updateHotRegion(player, args)
    elseif command == "DeleteRegion" then
        deleteHotRegion(player, args)
    elseif command == "ExportConfig" then
        -- Admin command to export config
        if player:getAccessLevel() ~= "None" then
            exportConfig()
            sendServerCommand(player, "RegionManager", "ExportComplete", {})
        end
    end
end

